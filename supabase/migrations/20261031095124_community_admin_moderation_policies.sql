-- Allow trusted admins to review reports and moderate published community content.
-- Authorization uses app_metadata, which members cannot edit themselves.

create policy "Admins moderate community reports"
on public.community_reports
for update
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin')
with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

